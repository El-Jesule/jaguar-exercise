import fs from 'node:fs'

const SOURCE = 'scripts/data/ne_110m_admin_0_countries.geojson'
const OUTPUT = 'src/features/map/country-paths.ts'
const VIEWBOX_WIDTH = 1000
const PADDING = 10
const SIMPLIFY_TOLERANCE = 0.35
const MIN_POLYGON_AREA = 0.4

const COUNTRY_ISO = [
  ['mx', 'MX'],
  ['gt', 'GT'],
  ['bz', 'BZ'],
  ['hn', 'HN'],
  ['ni', 'NI'],
  ['cr', 'CR'],
  ['pa', 'PA'],
  ['co', 'CO'],
  ['ve', 'VE'],
  ['gy', 'GY'],
  ['sr', 'SR'],
  ['gf', 'FR'],
  ['ec', 'EC'],
  ['pe', 'PE'],
  ['bo', 'BO'],
  ['br', 'BR'],
  ['py', 'PY'],
  ['ar', 'AR'],
]

const geojson = JSON.parse(fs.readFileSync(SOURCE, 'utf8'))

function isoOf(feature) {
  const { ISO_A2_EH: eh, ISO_A2: plain } = feature.properties
  return eh !== '-99' ? eh : plain
}

function toMercator([lon, lat]) {
  const clamped = Math.max(-85, Math.min(85, lat))
  return [
    (lon * Math.PI) / 180,
    Math.log(Math.tan(Math.PI / 4 + (clamped * Math.PI) / 360)),
  ]
}

function polygonsOf(feature) {
  const { type, coordinates } = feature.geometry
  return type === 'Polygon' ? [coordinates] : coordinates
}

function centroidX(polygon) {
  const ring = polygon[0]
  const total = ring.reduce((sum, point) => sum + point[0], 0)
  return total / ring.length
}

function ringArea(ring) {
  let area = 0
  for (let index = 0; index < ring.length - 1; index += 1) {
    const [x1, y1] = ring[index]
    const [x2, y2] = ring[index + 1]
    area += x1 * y2 - x2 * y1
  }
  return Math.abs(area / 2)
}

function perpendicularDistance(point, start, end) {
  const [px, py] = point
  const [x1, y1] = start
  const [x2, y2] = end
  const dx = x2 - x1
  const dy = y2 - y1
  const lengthSquared = dx * dx + dy * dy

  if (lengthSquared === 0) {
    return Math.hypot(px - x1, py - y1)
  }

  const t = Math.max(0, Math.min(1, ((px - x1) * dx + (py - y1) * dy) / lengthSquared))
  return Math.hypot(px - (x1 + t * dx), py - (y1 + t * dy))
}

function simplify(points, tolerance) {
  if (points.length < 3) {
    return points
  }

  let maxDistance = 0
  let index = 0

  for (let position = 1; position < points.length - 1; position += 1) {
    const distance = perpendicularDistance(points[position], points[0], points.at(-1))
    if (distance > maxDistance) {
      maxDistance = distance
      index = position
    }
  }

  if (maxDistance <= tolerance) {
    return [points[0], points.at(-1)]
  }

  const left = simplify(points.slice(0, index + 1), tolerance)
  const right = simplify(points.slice(index), tolerance)
  return [...left.slice(0, -1), ...right]
}

const collected = []

for (const [id, iso] of COUNTRY_ISO) {
  const feature = geojson.features.find((candidate) => isoOf(candidate) === iso)

  if (!feature) {
    throw new Error(`Missing feature for ${id} (${iso})`)
  }

  let polygons = polygonsOf(feature)

  if (id === 'gf') {
    polygons = polygons.filter((polygon) => centroidX(polygon) < -30)
  }

  collected.push({ id, polygons })
}

const allPoints = collected.flatMap(({ polygons }) =>
  polygons.flatMap((polygon) => polygon.flatMap((ring) => ring.map(toMercator))),
)

const xs = allPoints.map(([x]) => x)
const ys = allPoints.map(([, y]) => y)
const minX = Math.min(...xs)
const maxX = Math.max(...xs)
const minY = Math.min(...ys)
const maxY = Math.max(...ys)

const scale = (VIEWBOX_WIDTH - 2 * PADDING) / (maxX - minX)
const height = Math.round((maxY - minY) * scale + 2 * PADDING)

const project = ([lon, lat]) => {
  const [x, y] = toMercator([lon, lat])
  return [
    Math.round(((x - minX) * scale + PADDING) * 10) / 10,
    Math.round(((maxY - y) * scale + PADDING) * 10) / 10,
  ]
}

const shapes = collected.map(({ id, polygons }) => {
  const paths = polygons
    .filter((polygon) => {
      const projected = polygon[0].map(project)
      return ringArea(projected) >= MIN_POLYGON_AREA
    })
    .map((polygon) =>
      polygon
        .map((ring) => {
          const projected = ring.map(project)
          const simplified = simplify(projected, SIMPLIFY_TOLERANCE)
          const [first, ...rest] = simplified
          const segments = rest.map(([x, y]) => `L${x} ${y}`)
          return `M${first[0]} ${first[1]}${segments.join('')}Z`
        })
        .join(' '),
    )
    .filter((path) => path.length > 0)

  return { id, paths }
})

for (const { id, paths } of shapes) {
  if (paths.length === 0) {
    throw new Error(`Country ${id} produced no drawable path`)
  }
}

const body = shapes
  .map(({ id, paths }) => `  ${id}: [\n${paths.map((path) => `    '${path}',`).join('\n')}\n  ],`)
  .join('\n')

const output = `// Generated by scripts/build-map.mjs from Natural Earth 1:110m admin-0 (public domain).
// Do not edit by hand: run \`node scripts/build-map.mjs\` to regenerate.

export const MAP_VIEWBOX = '0 0 ${VIEWBOX_WIDTH} ${height}'

export const COUNTRY_SHAPES: Readonly<Record<string, readonly string[]>> = {
${body}
}
`

fs.writeFileSync(OUTPUT, output)

const bytes = Buffer.byteLength(output)
console.log(`Wrote ${OUTPUT} (${bytes} bytes, viewBox ${VIEWBOX_WIDTH}x${height}, ${shapes.length} countries)`)
